// Keep Quick View identical to the static, accessible project summaries.
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '../dist');
const labels = ['What', 'Why', 'Goal', 'My Role', 'How', 'Challenges', 'Target Users', 'Results'];
const text = html => html.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&nbsp;/g, ' ').replace(/&mdash;/g, '—').replace(/&ndash;/g, '–').replace(/\s+/g, ' ').trim();
const briefs = {};
for (const file of fs.readdirSync(root).filter(file => file.endsWith('.html'))) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const summary = html.match(/<ol class="project-brief-grid">([\s\S]*?)<\/ol>/);
  if (!summary) continue;
  const items = [...summary[1].matchAll(/<li>\s*<h3>\s*<span>\d+<\/span>([\s\S]*?)<\/h3>\s*<p>([\s\S]*?)<\/p>\s*<\/li>/g)].map(([,label,body]) => [text(label), text(body)]);
  assert.deepEqual(items.map(([label])=>label), labels, `${file}: required summary order`);
  const words = items.reduce((count,[,body])=>count+body.split(/\s+/).length,0);
  assert(words <= 180, `${file}: summary exceeds 180 words (${words})`);
  assert(items.every(([,body])=>body.length>0), `${file}: empty summary field`);
  briefs[file] = items;
  console.log(`${file}: ${words} words, 8 ordered fields`);
}
for (const file of ['dashboard-data-modelling.html','database-projects.html','system-analysis-projects.html','web-development-projects.html']) assert(briefs[file], `${file}: summary missing`);
fs.writeFileSync(path.join(root, 'assets/project-briefs.js'), '// Generated by scripts/sync-project-briefs.cjs from the static project pages.\nwindow.portfolioProjectBriefs = ' + JSON.stringify(briefs,null,2) + ';\n');
